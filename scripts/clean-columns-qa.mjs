function formatCardsHtml(qList) {
  const cards = qList.map((item, idx) => {
    const qNum = `Q${idx + 1}`;
    return `  <div class="p-4 sm:p-5 bg-[#F9FAF8] rounded-2xl border border-[#E2EAE5] space-y-1.5">
    <div class="font-extrabold text-sm sm:text-base text-[#2F5D50] flex items-start gap-2">
      <span class="bg-[#2F5D50] text-white text-xs px-2 py-0.5 rounded-md font-bold mt-0.5 shrink-0">${qNum}</span>
      <span>${item.q}</span>
    </div>
    <p class="text-xs sm:text-sm text-[#4E6159] leading-relaxed pl-7">
      ${item.a}
    </p>
  </div>`;
  }).join('\n');

  return `<div class="space-y-3.5 my-6 not-prose">\n${cards}\n</div>`;
}

console.log('[Clean-QA] Upgrading all 7 core columns with clean Q&A cards and safe spacing...');

const files = fs.readdirSync(columnDir).filter(f => f.endsWith('.md') && f !== '_index.md');

files.forEach(f => {
  const slug = f.replace('.md', '');
  const filePath = path.join(columnDir, f);
  let content = fs.readFileSync(filePath, 'utf8');

  // 프론트매터와 본문 분리
  const fmMatch = content.match(/^---([\s\S]*?)---\r?\n([\s\S]*)$/);
  if (!fmMatch) return;

  let fm = fmMatch[1];
  let body = fmMatch[2];

  // 불필요한 가로 구분선 (---) 모두 제거
  body = body.replace(/\n\s*---\s*\n/g, '\n\n');

  // Q&A 데이터가 정의되어 있는 경우 교체
  if (QA_DATA[slug]) {
    const newCardsHtml = formatCardsHtml(QA_DATA[slug]);
    
    // 기존 Q&A 섹션 치환
    if (body.includes('### 5. 진료실 자주 묻는 질문') || body.includes('### 5. 자주 묻는 질문')) {
      body = body.replace(/### 5\.\s*(?:진료실\s*)?자주 묻는 질문[\s\S]*?(?=### 6\.|\n>\s*\*\*권형근|$)/, `### 5. 진료실 자주 묻는 질문 (Q&A)\n\n${newCardsHtml}\n\n`);
    }
  }

  // 본문 내 시간/기간 물결표(~)를 공백 포함 ' ~ ' 로 안전하게 표준화
  body = body.replace(/(\d+)\s*~\s*(\d+)/g, '$1 ~ $2');
  body = body.replace(/(\d+)\s*～\s*(\d+)/g, '$1 ~ $2');

  const newContent = `---\n${fm.trim()}\n---\n\n${body.trim()}\n`;
  fs.writeFileSync(filePath, newContent, 'utf8');
  console.log(`✅ [${f}] Cleaned & verified.`);
});

